function [threshold, source] = factor2VoiceGate(roll, db, cfg, digitModel)
%FACTOR2VOICEGATE Factor 2 ONLY, using calibration tied to digit-only model.
% Never uses older mixed-speech Factor2VoiceCalibration.mat files.
% Factor 1's gate and trained threshold are NOT changed by this function.
if nargin < 3 || isempty(cfg), cfg = vsConfig(); end
threshold = cfg.ChallengeVoiceGate;
source = 'digit-only baseline (not calibrated)';
if nargin < 4 || isempty(digitModel) || ...
        ~isfile(cfg.Factor2CalibrationFile)
    return;
end
try
    c = load(cfg.Factor2CalibrationFile,'Entries');
    if ~isfield(c,'Entries') || ~isstruct(c.Entries), return; end
    for i = 1:numel(c.Entries)
        e = c.Entries(i);
        required = {'Roll','Calibrated','Threshold','ModelVersion', ...
            'DigitModelBuildTimestamp','PipelineVersion', ...
            'DatabaseBuildDate','NoiseMode','NumStudents', ...
            'NumGenuine','NumImpostor'};
        if ~all(isfield(e,required)), continue; end
        if ~strcmp(e.Roll,char(roll)) || ~e.Calibrated || ...
                ~isscalar(e.Threshold) || ~isfinite(e.Threshold) || ...
                ~isequal(e.ModelVersion,digitModel.ModelVersion) || ...
                ~isequal(e.DigitModelBuildTimestamp,digitModel.BuildTimestamp) || ...
                ~strcmp(e.PipelineVersion,cfg.PipelineVersion) || ...
                ~strcmp(e.DatabaseBuildDate,db.BuildDate) || ...
                ~strcmp(e.NoiseMode,digitVoiceNoiseMode(cfg)) || ...
                e.NumStudents ~= numel(digitModel.Rolls)
            continue;
        end
        threshold = e.Threshold;
        source = sprintf('digit-only live calibration for %s (%d genuine, %d impostor)', ...
            e.Roll,e.NumGenuine,e.NumImpostor);
        return;
    end
catch ME
    warning('ParkingSecuritySystem:DigitCalibrationIgnored', ...
        'Digit voice calibration was ignored: %s',ME.message);
end
end
