function model = checkDigitVoiceReady(cfg, db)
%CHECKDIGITVOICEREADY Validate independent Factor 2 model; never trains.
% Fail BEFORE recording audio if the external digit model is missing/stale.
if nargin < 1 || isempty(cfg), cfg = vsConfig(); end
if ~isfile(cfg.DigitVoiceModelFile)
    error('ParkingSecuritySystem:MissingDigitModel', ...
        ['DigitVoiceModel.mat is missing from the sibling database/ folder. ' ...
         'Run ENROLL_STUDENTS.m (does not modify valid Factor 1 models).']);
end
if nargin < 2 || isempty(db)
    if ~isfile(cfg.DatabaseFile)
        error('ParkingSecuritySystem:NoDatabase','Run ENROLL_STUDENTS.m first.');
    end
    db = load(cfg.DatabaseFile,'Students','BuildDate','DatabaseVersion');
end
try
    s = load(cfg.DigitVoiceModelFile,'DigitVoiceModel');
    model = s.DigitVoiceModel;
catch ME
    error('ParkingSecuritySystem:UnreadableDigitModel', ...
        'Cannot read DigitVoiceModel.mat (%s). Run ENROLL_STUDENTS.m.',ME.message);
end
valid = isstruct(model) && isscalar(model);
required = {'ModelVersion','BuildTimestamp','SourceDatabaseBuildDate', ...
    'SourceDatabaseVersion','SourcePipelineVersion','StudentRollsAtTraining', ...
    'Rolls','StudentIndices','UBM','VoiceMeans','Parameters'};
if valid, valid = all(isfield(model,required)); end
if valid
    valid = isequal(model.ModelVersion,1) && ...
        isequal(model.SourceDatabaseVersion,db.DatabaseVersion) && ...
        strcmp(model.SourceDatabaseBuildDate,db.BuildDate) && ...
        strcmp(model.SourcePipelineVersion,cfg.PipelineVersion) && ...
        isequal(model.StudentRollsAtTraining,{db.Students.Roll}) && ...
        isequal(model.Parameters,digitVoiceParameters(cfg)) && ...
        iscell(model.Rolls) && numel(model.Rolls)>=2 && ...
        numel(unique(model.Rolls))==numel(model.Rolls) && ...
        all(model.StudentIndices>=1) && ...
        all(model.StudentIndices<=numel(db.Students)) && ...
        numel(model.StudentIndices)==numel(model.Rolls) && ...
        isequal({db.Students(model.StudentIndices).Roll},model.Rolls) && ...
        size(model.VoiceMeans,3)==numel(model.Rolls) && ...
        size(model.VoiceMeans,1)==model.UBM.K && ...
        size(model.VoiceMeans,2)==size(model.UBM.mu,2);
end
if ~valid
    error('ParkingSecuritySystem:OutdatedDigitModel', ...
        ['DigitVoiceModel.mat is incompatible with current enrollment or ' ...
         'configuration. Run ENROLL_STUDENTS.m to rebuild the digit-only model.']);
end
end
