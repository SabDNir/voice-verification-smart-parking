function checkModelsReady(cfg)
%CHECKMODELSREADY  Validate the persistent trained models for live login.
% This function never enrolls, trains, writes files or needs raw recordings.
if nargin < 1, cfg = vsConfig(); end
helpText = ['Run ENROLL_STUDENTS.m to build or update your models. ' ...
            'Do not place the database/ folder inside ParkingSecuritySystem/.'];

if ~isfile(cfg.DatabaseFile)
    error('ParkingSecuritySystem:NoDatabase', ...
          'Missing %s\n%s', cfg.DatabaseFile, helpText);
end
if ~isfile(cfg.VerifierModelFile)
    error('ParkingSecuritySystem:NoVerifier', ...
          'Missing %s\n%s', cfg.VerifierModelFile, helpText);
end
try
    s = load(cfg.DatabaseFile, 'DatabaseVersion', 'ConfigUsed', 'Students', 'UBM');
catch ME
    error('ParkingSecuritySystem:InvalidDatabase', ...
          'Cannot open EnrolledDatabase.mat: %s\n%s', ME.message, helpText);
end
if ~isfield(s, 'DatabaseVersion') || s.DatabaseVersion < 6 || ...
        ~isfield(s, 'ConfigUsed') || ...
        ~isfield(s.ConfigUsed, 'PipelineVersion') || ...
        ~strcmp(s.ConfigUsed.PipelineVersion, cfg.PipelineVersion) || ...
        ~isfield(s, 'Students') || isempty(s.Students) || ...
        ~isfield(s.Students, 'Digits') || ~isfield(s, 'UBM')
    error('ParkingSecuritySystem:StaleDatabase', ...
          'Enrollment format is missing, incomplete or incompatible. %s', helpText);
end
try
    v = load(cfg.VerifierModelFile, 'VerifierModel');
catch ME
    error('ParkingSecuritySystem:InvalidVerifier', ...
          'Cannot open VerifierModel.mat: %s\n%s', ME.message, helpText);
end
if ~isfield(v, 'VerifierModel') || ~isstruct(v.VerifierModel) || ...
        ~isfield(v.VerifierModel, 'ThetaPhrase') || ...
        ~isfield(v.VerifierModel, 'NumStudents') || ...
        v.VerifierModel.NumStudents ~= numel(s.Students)
    error('ParkingSecuritySystem:StaleVerifier', ...
          'Verifier model is missing or mismatched with enrolled students. %s', helpText);
end
% Confirm that the trained verifier is not older than the enrollment it
% depends on. This does not scan raw_records or launch automatic training.
a = dir(cfg.DatabaseFile);
b = dir(cfg.VerifierModelFile);
if (b.datenum + 0.5/86400) < a.datenum
    error('ParkingSecuritySystem:OutdatedVerifier', ...
          'VerifierModel.mat is older than EnrolledDatabase.mat. %s', helpText);
end
end
