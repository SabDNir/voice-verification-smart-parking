function p = digitVoiceParameters(cfg)
%DIGITVOICEPARAMETERS Signature of settings that change digit-only training.
if nargin < 1 || isempty(cfg), cfg = vsConfig(); end
p = struct('NumMixtures',cfg.NumMixtures, ...
    'EMIterations',cfg.EMIterations, ...
    'LBGIterations',cfg.LBGIterations, ...
    'UBMMaxFrames',cfg.UBMMaxFrames, ...
    'MAPRelevance',cfg.MAPRelevance, ...
    'NumSpeakerCep',cfg.NumSpeakerCep, ...
    'DigitVoiceMaxTakesPerDigit',cfg.DigitVoiceMaxTakesPerDigit, ...
    'DigitVoiceFramesPerStudent',cfg.DigitVoiceFramesPerStudent, ...
    'DigitVoiceMinFramesPerDigit',cfg.DigitVoiceMinFramesPerDigit, ...
    'DigitVoiceMinFramesPerStudent',cfg.DigitVoiceMinFramesPerStudent);
end
